describe("real Neovim windows", function()
  after_each(function()
    vim.cmd("only!")
  end)
  it("moves into an unnamed buffer without a reload error", function()
    package.loaded.rex = nil
    vim.cmd("enew!")
    vim.cmd("vsplit")
    local previous = vim.api.nvim_get_current_win()
    local moved, destination = require("rex").move_right()
    assert.is_true(moved)
    assert.are.equal("nvim", destination)
    assert.are_not.equal(previous, vim.api.nvim_get_current_win())
  end)
end)
